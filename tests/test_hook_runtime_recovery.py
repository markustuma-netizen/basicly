from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from basicly import codex_hooks, hooks, lefthook_config
from basicly.catalog import bundled_catalog_root


@pytest.fixture
def repo(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.setenv("UV_CACHE_DIR", str(tmp_path / "uv-cache"))
    monkeypatch.setenv("UV_PYTHON", sys.executable)
    monkeypatch.setenv("UV_PYTHON_DOWNLOADS", "never")
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    destination = tmp_path / ".basicly/core/hooks"
    destination.mkdir(parents=True)
    shutil.copyfile(
        bundled_catalog_root() / "hooks/lefthook-runtime.py", destination / "lefthook-runtime.py"
    )
    return tmp_path


def invoke(
    repo: Path, manager: str, stage: str, payload: dict | None = None
) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(repo / ".basicly/core/hooks/lefthook-runtime.py"), manager, stage],
        cwd=repo,
        input=json.dumps(payload or {}),
        text=True,
        capture_output=True,
        check=False,
    )


@pytest.mark.parametrize(
    "manager,stage",
    [
        ("codex", "pretooluse"),
        ("codex", "sessionstart"),
        ("claude", "pretooluse"),
        ("copilot", "sessionstart"),
        ("git", "pre-commit"),
    ],
)
def test_missing_runtime_names_repair_without_exposing_machine_paths(
    repo: Path, manager: str, stage: str
) -> None:
    result = invoke(repo, manager, stage, {"tool_name": "apply_patch"})
    assert result.returncode == 2
    assert result.stdout == ""
    assert "Lefthook runtime is missing" in result.stderr
    assert "hooks-build --runtime-only" in result.stderr
    assert "hooks-check" in result.stderr
    assert str(repo) not in result.stderr


def test_runtime_only_repair_preserves_codex_configuration_and_generated_file_guard(
    repo: Path,
) -> None:
    scripts = repo / ".basicly/core/hooks"
    shutil.copyfile(bundled_catalog_root() / "hooks/protect-generated.py", scripts / "guard.py")
    specs = [
        hooks.HookSpec("guard", "guard.py", "pretooluse", manager="codex", matcher="apply_patch")
    ]
    lefthook_config.sync_config(repo, specs, ".basicly/core/hooks")
    codex_hooks.sync_hooks(repo, specs, ".basicly/core/hooks")
    configs = [
        repo / name for name in ("lefthook.yml", ".basicly/lefthook.yml", ".codex/hooks.json")
    ]
    before = {path: path.read_bytes() for path in configs}
    repair = subprocess.run(
        [sys.executable, "-m", "basicly.cli", "hooks-build", "--runtime-only"],
        cwd=repo,
        text=True,
        capture_output=True,
        check=False,
    )
    assert repair.returncode == 0, repair.stdout + repair.stderr
    assert {path: path.read_bytes() for path in configs} == before
    for filename, content, expected in (
        ("plain.md", "ordinary content\n", 0),
        ("generated.md", "Generated by basicly\n", 2),
    ):
        (repo / filename).write_text(content, encoding="utf-8")
        result = invoke(
            repo,
            "codex",
            "pretooluse",
            {
                "cwd": str(repo),
                "tool_name": "apply_patch",
                "tool_input": {
                    "command": f"*** Begin Patch\n*** Update File: {filename}\n*** End Patch"
                },
            },
        )
        assert result.returncode == expected, result.stderr
